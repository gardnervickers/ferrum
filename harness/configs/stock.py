#!/usr/bin/env python3
"""A stock LinuxCNC simulator config with millgui as its display.

    stock.py OUT_DIR --units mm|inch --axes XYZ|XYZA|XYYZ

What a new millgui user's machine looks like: a plain INI in the style of
LinuxCNC's configs/sim/axis (its INCREMENTS line included), with millgui's
probe macros on SUBROUTINE_PATH as `millgui --check --write-ini` sets it up;
joints looped back, a stock block that trips the probe input (signal `sim-probe` trips it by hand), tool changes acknowledged at
once, spindle always at speed. No Probe Basic, no mymill HAL, no pendant.
For the harness only; it never talks to a machine.
"""
import argparse
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]

# Limits and speeds per unit system: (min, max) per axis, max vel, accel.
LIMITS = {
    "mm": {"X": (-200, 200), "Y": (-150, 150), "Z": (-150, 0), "vel": 50, "acc": 500,
           # LinuxCNC's axis_mm.ini increments, as stock configs write them.
           "increments": "1 mm, .01 in, .1mm, 1 mil, .1 mil, 1/8000 in",
           "jog": 25, "maxjog": 50},
    "inch": {"X": (-8, 8), "Y": (-6, 6), "Z": (-6, 0), "vel": 2, "acc": 20,
             # LinuxCNC's axis.ini increments.
             "increments": ".1in .05in .01in .005in .001in .0005in .0001in",
             "jog": 1, "maxjog": 2},
}

# A block of stock on the table, in machine coordinates: X and Y ranges, the
# top Z, and the probe ball's radius (T99's D/2). The probe input trips while
# the tool tip (machine Z minus the tool length) is inside it, its sides
# pushed out by the radius, as a ball touching the block would.
BLOCK = {
    "mm": {"x": (40, 120), "y": (-60, -10), "top": -100, "r": 1.0},
    "inch": {"x": (1.5, 4.5), "y": (-2.5, -0.5), "top": -4.0, "r": 0.04},
}

TOOLS = {
    "mm": ["T1 P1 D6.0 Z30.0 ;6mm endmill", "T2 P2 D10.0 Z45.0 ;10mm endmill", "T3 P3 D3.0 Z25.0 ;3mm drill",
           "T99 P99 D2.0 Z60.0 ;probe"],
    "inch": ["T1 P1 D0.25 Z1.2 ;1/4 endmill", "T2 P2 D0.5 Z1.8 ;1/2 endmill", "T3 P3 D0.125 Z1.0 ;1/8 drill",
             "T99 P99 D0.08 Z2.4 ;probe"],
}


def ini(out: Path, units: str, axes: str) -> str:
    L = LIMITS[units]
    joints = len(axes)
    s = f"""# Generated by millgui/harness/configs/stock.py: a stock {units} {axes} simulator.
[EMC]
VERSION = 1.1
MACHINE = harness-{units}-{axes.lower()}
DEBUG = 0

[DISPLAY]
DISPLAY = ./display
CYCLE_TIME = 0.100
POSITION_OFFSET = RELATIVE
POSITION_FEEDBACK = ACTUAL
MAX_FEED_OVERRIDE = 1.2
MAX_SPINDLE_OVERRIDE = 1.0
PROGRAM_PREFIX = {out / 'nc_files'}
INCREMENTS = {L['increments']}
DEFAULT_LINEAR_VELOCITY = {L['jog']}
MAX_LINEAR_VELOCITY = {L['maxjog']}
DEFAULT_ANGULAR_VELOCITY = 90
MAX_ANGULAR_VELOCITY = 180

[MILLGUI]
# The core modules; a stock machine has no drawbar, drives or interlock HAL.
MODULES = run job manual probe tools offsets conv files util

[TASK]
TASK = milltask
CYCLE_TIME = 0.001

[RS274NGC]
PARAMETER_FILE = sim.var
SUBROUTINE_PATH = {out / 'subroutines'}:{REPO / 'millgui' / 'macros'}

[EMCMOT]
EMCMOT = motmod
COMM_TIMEOUT = 1.0
SERVO_PERIOD = 1000000

[EMCIO]
EMCIO = io
CYCLE_TIME = 0.100
TOOL_TABLE = tool.tbl

[HAL]
HALFILE = sim.hal
HALUI = halui

[TRAJ]
COORDINATES = {' '.join(dict.fromkeys(axes))}
LINEAR_UNITS = {units}
ANGULAR_UNITS = degree
DEFAULT_LINEAR_VELOCITY = {L['vel'] / 2}
MAX_LINEAR_VELOCITY = {L['vel']}
DEFAULT_LINEAR_ACCELERATION = {L['acc']}
MAX_LINEAR_ACCELERATION = {L['acc']}

[KINS]
KINEMATICS = trivkins coordinates={axes}
JOINTS = {joints}
"""
    for j, a in enumerate(axes):
        if a == "A":
            lo, hi, vel, acc, typ = -99999, 99999, 180, 900, "ANGULAR"
        else:
            (lo, hi), vel, acc, typ = L[a], L["vel"], L["acc"], "LINEAR"
        # A gantry (XYYZ) has one [AXIS_Y] for its two Y joints.
        if a not in axes[:j]:
            s += f"""
[AXIS_{a}]
MAX_VELOCITY = {vel}
MAX_ACCELERATION = {acc}
MIN_LIMIT = {lo}
MAX_LIMIT = {hi}
"""
        s += f"""
[JOINT_{j}]
TYPE = {typ}
HOME = 0
MAX_VELOCITY = {vel}
MAX_ACCELERATION = {acc}
MIN_LIMIT = {lo}
MAX_LIMIT = {hi}
FERROR = 1
MIN_FERROR = 0.25
# Homes in place (no switches): HOME ALL is immediate.
HOME_OFFSET = 0
HOME_SEARCH_VEL = 0
HOME_LATCH_VEL = 0
HOME_USE_INDEX = NO
HOME_SEQUENCE = {0 if a == 'Z' else 1}
"""
    s += """
[SPINDLE_0]
MAX_FORWARD_VELOCITY = 6000
MAX_REVERSE_VELOCITY = 6000
"""
    return s


def hal(axes: str, toolchange: str, units: str) -> str:
    s = """# Generated by stock.py: joints looped back, nothing else simulated.
loadrt [KINS]KINEMATICS
loadrt [EMCMOT]EMCMOT servo_period_nsec=[EMCMOT]SERVO_PERIOD num_joints=[KINS]JOINTS
addf motion-command-handler servo-thread
addf motion-controller servo-thread
"""
    for j in range(len(axes)):
        s += f"net j{j}-pos joint.{j}.motor-pos-cmd => joint.{j}.motor-pos-fb\n"
    s += """net estop-loop iocontrol.0.user-enable-out => iocontrol.0.emc-enable-in
net tool-prep-loop iocontrol.0.tool-prepare => iocontrol.0.tool-prepared
""" + ("net tool-change-loop iocontrol.0.tool-change => iocontrol.0.tool-changed\n" if toolchange == "loop" else
       "# M6 is answered by millgui's tool change dialog (its toolchange module).\n") + """setp spindle.0.at-speed 1
"""
    b = BLOCK[units]
    (x0, x1), (y0, y1), r = b["x"], b["y"], b["r"]
    s += f"""
# The stock block (stock.py BLOCK): X {x0}..{x1}, Y {y0}..{y1}, top Z {b["top"]}.
loadrt wcomp count=3
loadrt sum2 count=1
loadrt logic count=2 personality=0x103,0x202
addf sum2.0 servo-thread
addf wcomp.0 servo-thread
addf wcomp.1 servo-thread
addf wcomp.2 servo-thread
addf logic.0 servo-thread
addf logic.1 servo-thread
setp wcomp.0.min {x0 - r}
setp wcomp.0.max {x1 + r}
setp wcomp.1.min {y0 - r}
setp wcomp.1.max {y1 + r}
setp wcomp.2.min -1e9
setp wcomp.2.max {b["top"]}
setp sum2.0.gain1 -1
net block-x axis.x.pos-cmd => wcomp.0.in
net block-y axis.y.pos-cmd => wcomp.1.in
net block-z axis.z.pos-cmd => sum2.0.in0
net block-tlo motion.tooloffset.z => sum2.0.in1
net block-tip sum2.0.out => wcomp.2.in
net block-in-x wcomp.0.out => logic.0.in-00
net block-in-y wcomp.1.out => logic.0.in-01
net block-in-z wcomp.2.out => logic.0.in-02
net block-touch logic.0.and => logic.1.in-00
# The harness can also trip the probe by hand: hal sim-probe 1
net sim-probe => logic.1.in-01
net probe-in logic.1.or => motion.probe-input
"""
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("--units", choices=["mm", "inch"], default="mm")
    ap.add_argument("--axes", default="XYZ")
    # loop: tool changes acknowledged at once in HAL; dialog: nothing answers
    # M6 in HAL, so millgui's tool change dialog does.
    ap.add_argument("--toolchange", choices=["loop", "dialog"], default="loop")
    a = ap.parse_args()
    out = a.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    (out / "nc_files").mkdir(exist_ok=True)
    (out / "subroutines").mkdir(exist_ok=True)
    (out / "millgui.ini").write_text(ini(out, a.units, a.axes))
    (out / "sim.hal").write_text(hal(a.axes, a.toolchange, a.units))
    (out / "tool.tbl").write_text("\n".join(TOOLS[a.units]) + "\n")
    disp = out / "display"
    disp.write_text('#!/bin/sh\nexport SLINT_SCALE_FACTOR="${SLINT_SCALE_FACTOR:-1}"\n'
                    f'exec "${{MILLGUI_BIN:-{REPO}/millgui/target/release/millgui}}" "$@"\n')
    disp.chmod(0o755)
    for f in (REPO / "millgui" / "testdata" / "nc_files").glob("*.ngc"):
        shutil.copy(f, out / "nc_files" / f.name)
    # No millgui/hal beside the INI: millgui's modules connect their pins
    # themselves ([hal] in millgui.toml, or the defaults), as on a stranger's
    # machine. The repo's millgui/hal files are mymill's.


if __name__ == "__main__":
    main()
