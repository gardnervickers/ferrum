#!/usr/bin/env python3
"""A stock LinuxCNC simulator config with millgui as its display.

    stock.py OUT_DIR --units mm|inch --axes XYZ|XYZA

What a new millgui user's machine looks like: a plain INI in the style of
LinuxCNC's configs/sim/axis (its INCREMENTS line included), joints looped
back, a probe input on signal `sim-probe`, tool changes acknowledged at
once, spindle always at speed. No Probe Basic, no mymill HAL, no pendant.
For the harness only; it never talks to a machine.
"""
import argparse
import os
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]

# Limits and speeds per unit system: (min, max) per axis, max vel, accel.
LIMITS = {
    "mm": {"X": (-200, 200), "Y": (-150, 150), "Z": (-150, 0), "vel": 50, "acc": 500,
           # LinuxCNC's axis_mm.ini increments, as stock configs write them.
           "increments": "1 mm, .01 in, .1mm, 1 mil, .1 mil, 1/8000 in",
           "jog": 25, "maxjog": 50},
    "inch": {"X": (-8, 8), "Y": (-6, 6), "Z": (-6, 0), "vel": 2, "acc": 20,
             # LinuxCNC's axis.ini increments.
             "increments": ".1in .05in .01in .005in .001in .0005in .0001in",
             "jog": 1, "maxjog": 2},
}

TOOLS = {
    "mm": ["T1 P1 D6.0 Z30.0 ;6mm endmill", "T2 P2 D10.0 Z45.0 ;10mm endmill", "T3 P3 D3.0 Z25.0 ;3mm drill",
           "T99 P99 D2.0 Z60.0 ;probe"],
    "inch": ["T1 P1 D0.25 Z1.2 ;1/4 endmill", "T2 P2 D0.5 Z1.8 ;1/2 endmill", "T3 P3 D0.125 Z1.0 ;1/8 drill",
             "T99 P99 D0.08 Z2.4 ;probe"],
}


def ini(out: Path, units: str, axes: str) -> str:
    L = LIMITS[units]
    joints = len(axes)
    s = f"""# Generated by millgui/harness/configs/stock.py: a stock {units} {axes} simulator.
[EMC]
VERSION = 1.1
MACHINE = harness-{units}-{axes.lower()}
DEBUG = 0

[DISPLAY]
DISPLAY = ./display
CYCLE_TIME = 0.100
POSITION_OFFSET = RELATIVE
POSITION_FEEDBACK = ACTUAL
MAX_FEED_OVERRIDE = 1.2
MAX_SPINDLE_OVERRIDE = 1.0
PROGRAM_PREFIX = {out / 'nc_files'}
INCREMENTS = {L['increments']}
DEFAULT_LINEAR_VELOCITY = {L['jog']}
MAX_LINEAR_VELOCITY = {L['maxjog']}
DEFAULT_ANGULAR_VELOCITY = 90
MAX_ANGULAR_VELOCITY = 180

[MILLGUI]
# The core modules; a stock machine has no drawbar, drives or interlock HAL.
MODULES = run job manual probe tools offsets conv files util

[TASK]
TASK = milltask
CYCLE_TIME = 0.001

[RS274NGC]
PARAMETER_FILE = sim.var
SUBROUTINE_PATH = {out / 'subroutines'}

[EMCMOT]
EMCMOT = motmod
COMM_TIMEOUT = 1.0
SERVO_PERIOD = 1000000

[EMCIO]
EMCIO = io
CYCLE_TIME = 0.100
TOOL_TABLE = tool.tbl

[HAL]
HALFILE = sim.hal
HALUI = halui

[TRAJ]
COORDINATES = {' '.join(axes)}
LINEAR_UNITS = {units}
ANGULAR_UNITS = degree
DEFAULT_LINEAR_VELOCITY = {L['vel'] / 2}
MAX_LINEAR_VELOCITY = {L['vel']}
DEFAULT_LINEAR_ACCELERATION = {L['acc']}
MAX_LINEAR_ACCELERATION = {L['acc']}

[KINS]
KINEMATICS = trivkins coordinates={axes}
JOINTS = {joints}
"""
    for j, a in enumerate(axes):
        if a == "A":
            lo, hi, vel, acc, typ = -99999, 99999, 180, 900, "ANGULAR"
        else:
            (lo, hi), vel, acc, typ = L[a], L["vel"], L["acc"], "LINEAR"
        s += f"""
[AXIS_{a}]
MAX_VELOCITY = {vel}
MAX_ACCELERATION = {acc}
MIN_LIMIT = {lo}
MAX_LIMIT = {hi}

[JOINT_{j}]
TYPE = {typ}
HOME = 0
MAX_VELOCITY = {vel}
MAX_ACCELERATION = {acc}
MIN_LIMIT = {lo}
MAX_LIMIT = {hi}
FERROR = 1
MIN_FERROR = 0.25
# Homes in place (no switches): HOME ALL is immediate.
HOME_OFFSET = 0
HOME_SEARCH_VEL = 0
HOME_LATCH_VEL = 0
HOME_USE_INDEX = NO
HOME_SEQUENCE = {0 if a == 'Z' else 1}
"""
    s += """
[SPINDLE_0]
MAX_FORWARD_VELOCITY = 6000
MAX_REVERSE_VELOCITY = 6000
"""
    return s


def hal(axes: str) -> str:
    s = """# Generated by stock.py: joints looped back, nothing else simulated.
loadrt [KINS]KINEMATICS
loadrt [EMCMOT]EMCMOT servo_period_nsec=[EMCMOT]SERVO_PERIOD num_joints=[KINS]JOINTS
addf motion-command-handler servo-thread
addf motion-controller servo-thread
"""
    for j in range(len(axes)):
        s += f"net j{j}-pos joint.{j}.motor-pos-cmd => joint.{j}.motor-pos-fb\n"
    s += """net estop-loop iocontrol.0.user-enable-out => iocontrol.0.emc-enable-in
net tool-prep-loop iocontrol.0.tool-prepare => iocontrol.0.tool-prepared
net tool-change-loop iocontrol.0.tool-change => iocontrol.0.tool-changed
setp spindle.0.at-speed 1
# The harness trips the probe with: hal sim-probe 1
net sim-probe => motion.probe-input
"""
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("--units", choices=["mm", "inch"], default="mm")
    ap.add_argument("--axes", default="XYZ")
    a = ap.parse_args()
    out = a.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    (out / "nc_files").mkdir(exist_ok=True)
    (out / "subroutines").mkdir(exist_ok=True)
    (out / "millgui.ini").write_text(ini(out, a.units, a.axes))
    (out / "sim.hal").write_text(hal(a.axes))
    (out / "tool.tbl").write_text("\n".join(TOOLS[a.units]) + "\n")
    disp = out / "display"
    disp.write_text('#!/bin/sh\nexport SLINT_SCALE_FACTOR="${SLINT_SCALE_FACTOR:-1}"\n'
                    f'exec "${{MILLGUI_BIN:-{REPO}/millgui/target/release/millgui}}" "$@"\n')
    disp.chmod(0o755)
    for f in (REPO / "millgui" / "testdata" / "nc_files").glob("*.ngc"):
        shutil.copy(f, out / "nc_files" / f.name)
    # millgui finds its module HAL files under millgui/hal next to the INI.
    if not (out / "millgui").exists():
        os.symlink(REPO / "millgui", out / "millgui")


if __name__ == "__main__":
    main()
