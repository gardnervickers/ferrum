#!/usr/bin/env python3
"""Writes the probe bench's LinuxCNC config: make_config.py OUT --units mm|inch.

A headless XYZ simulator sized like Gardner's PM-728VT (mymill.ini's travel,
velocities and accelerations) so the mymill sim's workpieces (world.py) are
in reach. Ferrum's macros only on SUBROUTINE_PATH; the probe values are
mymill's probe_basic.var ones (converted for inch). The display is the
bench driver (bench.py), which runs the test cases and exits.
For the simulator only.
"""
import argparse
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
FERRUM = HERE.parents[1]

# mymill's probe_basic.var (mm): what Gardner's mill runs with.
PARAMS_MM = {
    3004: 1000, 3005: 100, 3006: 2000, 3007: 287.160032, 3008: 120, 3009: 5, 3010: 286.873159,
    3011: 0, 3012: 0, 3013: 1, 3014: 99, 3015: 80, 3016: 500, 3017: 800, 3018: 25, 3019: 4,
    3020: 50, 3021: 2, 3022: 0, 3023: 6, 3024: 50, 3025: 30, 3026: 40, 3027: 30, 3028: 15,
    3029: 15, 3030: 0, 3031: 0, 3032: 0.059025, 3033: 20, 3034: 30, 3035: 0, 3036: 0, 3037: 0,
}
# The ones that are not lengths or feeds (numbers, modes).
UNITLESS = {3011, 3012, 3013, 3014, 3030, 3031, 3036}

PROBE_D_MM = 3.175
PROBE_L_MM = 125.7175


def conv(n, v, units):
    if units == "mm" or n in UNITLESS:
        return v
    return v / 25.4


def write(out: Path, units: str):
    k = 1.0 if units == "mm" else 1 / 25.4
    out.mkdir(parents=True, exist_ok=True)
    f = lambda v: f"{v * k:.6f}"  # noqa: E731
    (out / "bench.ini").write_text(f"""# Generated by ferrum/harness/probe-bench/make_config.py ({units}).
[EMC]
VERSION = 1.1
MACHINE = probe-bench-{units}
DEBUG = 0

[DISPLAY]
DISPLAY = {out / 'display'}
CYCLE_TIME = 0.100
POSITION_OFFSET = RELATIVE
POSITION_FEEDBACK = ACTUAL
MAX_FEED_OVERRIDE = 2.0

[TASK]
TASK = milltask
CYCLE_TIME = 0.001

[RS274NGC]
PARAMETER_FILE = bench.var
SUBROUTINE_PATH = {FERRUM / 'macros'}
INI_VARS = 1
HAL_PIN_VARS = 1

[EMCMOT]
EMCMOT = motmod
COMM_TIMEOUT = 1.0
SERVO_PERIOD = 1000000

[EMCIO]
EMCIO = io
CYCLE_TIME = 0.100
TOOL_TABLE = tool.tbl

[HAL]
HALFILE = bench.hal

[TRAJ]
COORDINATES = X Y Z
LINEAR_UNITS = {units}
ANGULAR_UNITS = degree
DEFAULT_LINEAR_VELOCITY = {f(50)}
MAX_LINEAR_VELOCITY = {f(100)}
DEFAULT_LINEAR_ACCELERATION = {f(900)}
MAX_LINEAR_ACCELERATION = {f(900)}

[KINS]
KINEMATICS = trivkins coordinates=XYZ
JOINTS = 3

[AXIS_X]
MAX_VELOCITY = {f(100)}
MAX_ACCELERATION = {f(900)}
MIN_LIMIT = {f(-0.001)}
MAX_LIMIT = {f(430)}

[JOINT_0]
TYPE = LINEAR
HOME = 0
MAX_VELOCITY = {f(100)}
MAX_ACCELERATION = {f(900)}
MIN_LIMIT = {f(-0.001)}
MAX_LIMIT = {f(430)}
FERROR = {f(5)}
MIN_FERROR = {f(1)}
HOME_SEQUENCE = 1

[AXIS_Y]
MAX_VELOCITY = {f(100)}
MAX_ACCELERATION = {f(900)}
MIN_LIMIT = {f(-200)}
MAX_LIMIT = {f(0.001)}

[JOINT_1]
TYPE = LINEAR
HOME = 0
MAX_VELOCITY = {f(100)}
MAX_ACCELERATION = {f(900)}
MIN_LIMIT = {f(-200)}
MAX_LIMIT = {f(0.001)}
FERROR = {f(5)}
MIN_FERROR = {f(1)}
HOME_SEQUENCE = 1

[AXIS_Z]
MAX_VELOCITY = {f(50)}
MAX_ACCELERATION = {f(500)}
MIN_LIMIT = {f(-350)}
MAX_LIMIT = {f(0.001)}

[JOINT_2]
TYPE = LINEAR
HOME = 0
MAX_VELOCITY = {f(50)}
MAX_ACCELERATION = {f(500)}
MIN_LIMIT = {f(-350)}
MAX_LIMIT = {f(0.001)}
FERROR = {f(5)}
MIN_FERROR = {f(1)}
HOME_SEQUENCE = 0

[TOOL_SETTER]
SPINDLE_NOSE_DIAMETER = {f(40)}

[SPINDLE_0]
MAX_FORWARD_VELOCITY = 6000
""")
    (out / "bench.hal").write_text(f"""# Generated by make_config.py: joints looped back, world.py as the probe.
loadrt [KINS]KINEMATICS
loadrt [EMCMOT]EMCMOT servo_period_nsec=[EMCMOT]SERVO_PERIOD num_joints=[KINS]JOINTS
addf motion-command-handler servo-thread
addf motion-controller servo-thread
net j0 joint.0.motor-pos-cmd => joint.0.motor-pos-fb
net j1 joint.1.motor-pos-cmd => joint.1.motor-pos-fb
net j2 joint.2.motor-pos-cmd => joint.2.motor-pos-fb
net estop-loop iocontrol.0.user-enable-out => iocontrol.0.emc-enable-in
net tool-prep-loop iocontrol.0.tool-prepare => iocontrol.0.tool-prepared
net tool-change-loop iocontrol.0.tool-change => iocontrol.0.tool-changed
setp spindle.0.at-speed 1
loadusr -Wn world python3 {HERE / 'world.py'}
net wx joint.0.pos-fb => world.x
net wy joint.1.pos-fb => world.y
net wz joint.2.pos-fb => world.z
net wtool iocontrol.0.tool-number => world.tool
net wmtype motion.motion-type => world.motion-type
net wprobe world.probe => motion.probe-input
""")
    tools = [
        f"T99 P99 D{PROBE_D_MM * k:.6f} Z{PROBE_L_MM * k:.6f} ;probe",
        f"T1 P1 D{6 * k:.6f} Z{60 * k:.6f} ;6mm endmill",
        f"T2 P2 D{0:.6f} Z{100 * k:.6f} ;probe with no diameter",
    ]
    (out / "tool.tbl").write_text("\n".join(tools) + "\n")
    (out / "bench.var").write_text("".join(f"{n}\t{conv(n, v, units):.6f}\n" for n, v in sorted(PARAMS_MM.items())))
    disp = out / "display"
    disp.write_text(f'#!/bin/sh\nexec python3 "{HERE / "bench.py"}" "$@"\n')
    disp.chmod(0o755)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("--units", choices=["mm", "inch"], default="mm")
    a = ap.parse_args()
    write(a.out.resolve(), a.units)


if __name__ == "__main__":
    main()
